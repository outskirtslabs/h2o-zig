        var sdk_include_buf: [1024]u8 = undefined;
        const sdk_include = std.fmt.bufPrint(&sdk_include_buf, "{s}/usr/include", .{sdk_path}) catch unreachable;
        h2o.root_module.addSystemIncludePath(.{ .cwd_relative = sdk_include });
